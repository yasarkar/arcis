// Regenerates src/config/abis/v5.generated.ts from the Foundry build so the frontend ABI can never
// drift from the contracts.   Usage:  node scripts/gen-v5-abis.mjs
import { execFileSync } from 'node:child_process'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const contractsDir = resolve(root, 'contracts')

const targets = [
  ['STABLE_SWAP_V5_ABI', 'src/v5/StableSwapPoolV5.sol:StableSwapPoolV5'],
  ['ARCIS_SWAP_ROUTER_V5_ABI', 'src/v5/ArcisSwapRouterV5.sol:ArcisSwapRouterV5'],
  ['MANUAL_RATE_PROVIDER_ABI', 'src/v5/ManualRateProvider.sol:ManualRateProvider'],
]

let out = '// AUTO-GENERATED by scripts/gen-v5-abis.mjs — do not edit by hand.\n\n'
for (const [name, id] of targets) {
  const json = execFileSync('forge', ['inspect', id, 'abi', '--json'], { cwd: contractsDir, encoding: 'utf8' })
  out += `export const ${name} = ${JSON.stringify(JSON.parse(json), null, 2)} as const\n\n`
}

const file = resolve(root, 'src/config/abis/v5.generated.ts')
mkdirSync(dirname(file), { recursive: true })
writeFileSync(file, out)
console.log('wrote', file)
